"""HTTP API for the fine-tuned ticket classifier.

Run:   uvicorn src.api:app --port 8000
Try:   curl -X POST localhost:8000/classify -H 'Content-Type: application/json' \
            -d '{"text": "Outlook keeps asking for my password"}'
Docs:  http://localhost:8000/docs  (interactive, generated by FastAPI)
"""

from __future__ import annotations

from contextlib import asynccontextmanager
from typing import Callable

from fastapi import FastAPI, HTTPException, Request
from pydantic import BaseModel, Field

from src.predict import TicketClassifier


class TicketIn(BaseModel):
    text: str = Field(..., min_length=1, max_length=10_000, examples=["Outlook keeps asking for my password"])


class ClassificationOut(BaseModel):
    category: str
    confidence: float = Field(..., ge=0, le=1, description="Model probability for the chosen category")
    scores: dict[str, float] = Field(..., description="Probability for every category")


def create_app(classifier_factory: Callable[[], TicketClassifier] = TicketClassifier) -> FastAPI:
    """Build the app. Tests pass a factory that returns a fake classifier."""

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        app.state.classifier = classifier_factory()  # load the model once, at startup
        yield

    app = FastAPI(title="Support Ticket Classifier", version="1.0", lifespan=lifespan)

    @app.get("/health")
    def health(request: Request) -> dict:
        return {"status": "ok", "categories": request.app.state.classifier.labels}

    # Plain `def` (not async): FastAPI runs it in a worker thread, so CPU-heavy
    # inference doesn't block the server from accepting other requests.
    @app.post("/classify", response_model=ClassificationOut)
    def classify(ticket: TicketIn, request: Request) -> dict:
        if not ticket.text.strip():
            raise HTTPException(status_code=422, detail="Ticket text must not be blank.")
        return request.app.state.classifier.predict(ticket.text)

    return app


app = create_app()
